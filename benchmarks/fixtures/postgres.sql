DROP TABLE IF EXISTS post_tags, posts, tags, users CASCADE;
CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  name text NOT NULL
);
CREATE TABLE posts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  title text NOT NULL,
  author_id integer NOT NULL REFERENCES users(id),
  editor_id integer REFERENCES users(id),
  state text NOT NULL DEFAULT 'draft',
  views bigint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX posts_author_id_idx ON posts(author_id, created_at DESC, id DESC);
CREATE INDEX posts_state_created_idx ON posts(state, created_at DESC, id DESC);
CREATE TABLE tags (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label text NOT NULL UNIQUE
);
CREATE TABLE post_tags (
  post_id integer NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  tag_id integer NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
  PRIMARY KEY (post_id, tag_id)
);
CREATE INDEX post_tags_tag_id_idx ON post_tags(tag_id);
