const snapshot = schema({
  userProfiles: { id: int.auto, displayName: text.unique },
  posts: ({ userProfiles }) =>
    table({
      id: int.auto,
      title: text,
      state: oneOf("draft", "published").default("draft"),
      author: userProfiles,
      editor: userProfiles.nullable.inverse("edited"),
    })
      .indexes((posts) => ({
        title: index(posts.title)
          .unique.include(posts.state)
          .where(posts.state.is("published")),
      }))
      .checks((posts) => ({ title: posts.title.isNot("") })),
  labels: { id: int.auto, label: text },
  postLabels: ({ posts, labels }) => junction({ post: posts, label: labels }),
}).$snapshot();
const posts = snapshot.tables.find((table) => table.name === "posts")!;
const users = snapshot.tables.find((table) => table.name === "userProfiles")!;

test("inspect links physical foreign keys and logical reverse/through relationships to their targets", () => {
  expect(
    inspectEntries(posts, "Columns").find((entry) => entry.name === "editorId"),
  ).toMatchObject({
    badges: ["FK", "NULL"],
    target: { table: "user_profiles", column: "id" },
  });
  expect(
    inspectEntries(posts, "Relations").find((entry) => entry.name === "author"),
  ).toMatchObject({ target: { table: "userProfiles", column: "id" } });
  expect(
    inspectEntries(users, "Relations").find((entry) => entry.name === "edited"),
  ).toMatchObject({
    badges: ["REVERSE"],
    target: { table: "posts", column: "editorId" },
  });
  expect(
    inspectEntries(posts, "Relations").find((entry) => entry.name === "labels"),
  ).toMatchObject({ kind: "many ↔ many", target: { table: "labels" } });
  expect(
    inspectEntries(
      snapshot.tables.find((table) => table.name === "postLabels")!,
      "Columns",
    ).every((entry) => entry.badges.includes("PK")),
  ).toBe(true);
  expect(
    matchingTables(snapshot, "DISPLAY_NAME").map((table) => table.name),
  ).toEqual(["userProfiles"]);
  expect(matchingTables(snapshot, "user_profiles")).toContain(users);
  expect(matchingTables(snapshot, "no_such_field")).toEqual([]);
});

test("identity columns of both generations get the AUTO badge and their generation", () => {
  const counters = schema({
    counters: { id: int.auto, legacy: int.auto.byDefault },
  })
    .$snapshot()
    .tables.find((table) => table.name === "counters")!;
  const entries = inspectEntries(counters, "Columns");

  expect(entries.find((entry) => entry.name === "id")).toMatchObject({
    badges: ["PK", "AUTO"],
  });
  expect(entries.find((entry) => entry.name === "legacy")?.badges).toEqual([
    "AUTO",
  ]);
  expect(
    entries.find((entry) => entry.name === "legacy")?.description,
  ).toContain("GENERATED BY DEFAULT AS IDENTITY");
});

test("SQL tab includes enum definitions, constraints, partial/covering indexes and physical names", () => {
  const sql = inspectTableSQL(snapshot, posts);
  expect(sql).toContain('CREATE TYPE "posts_state_enum" AS ENUM');
  expect(sql).toContain('CREATE TABLE "posts"');
  expect(sql).toContain('REFERENCES "user_profiles" ("id")');
  expect(sql).toContain("GENERATED ALWAYS AS IDENTITY");
  expect(sql).toContain('PRIMARY KEY ("id")');
  expect(sql).toContain('CHECK ("title" <>');
  expect(sql).toContain("CREATE UNIQUE INDEX");
  expect(sql).toContain('INCLUDE ("state") WHERE');
  expect(sql).not.toContain('CREATE TABLE "user_profiles"');
  const details = inspectEntries(posts, "Indexes")[0]!;
  expect(details.description).toContain("Include:");
  expect(details.description).toContain("Where:");
});

test("SQL highlighting preserves literal SQL including escaped quotes, dollar strings and comments", () => {
  const sql = `-- CREATE 42\nCREATE TABLE "a""b" ("value" text DEFAULT E'can\\'t SELECT', "body" text DEFAULT $body$'SQL' $other$ text$body$, "日本語" integer DEFAULT 1e-3); /* NULL */`;
  const highlighted = highlightSQL(sql, true);
  expect(stripVTControlCharacters(highlighted)).toBe(sql);
  expect(highlighted).toContain("\u001b[");
  expect(highlightSQL(sql, false)).toBe(sql);
});

test("condition relations are listed with their cardinality and no foreign key", () => {
  const model = schema({
    users: { id: int.auto, name: text.unique },
    posts: ({ users }) =>
      table({ id: int.auto, title: text, authorName: text }).relations(
        (post, { to }) => ({
          author: to(users)
            .one((user) => post.authorName.is(user.name))
            .inverse("written"),
        }),
      ),
  }).$snapshot();
  const posts = model.tables.find((table) => table.name === "posts")!;
  const users = model.tables.find((table) => table.name === "users")!;

  expect(
    inspectEntries(posts, "Relations").find((entry) => entry.name === "author"),
  ).toMatchObject({
    kind: "one",
    badges: ["CONDITION"],
    target: { table: "users" },
  });
  expect(
    inspectEntries(users, "Relations").find(
      (entry) => entry.name === "written",
    ),
  ).toMatchObject({
    kind: "many",
    badges: ["CONDITION", "REVERSE"],
    description: expect.stringContaining("declared in posts.relations()"),
  });
  expect(
    inspectEntries(posts, "Columns").map((entry) => entry.name),
  ).not.toContain("authorId");
  expect(stripVTControlCharacters(formatSchema(model))).toContain(
    "author               one users by condition",
  );
  expect(
    stripVTControlCharacters(formatSchema(model, undefined, true)),
  ).toContain("posts.author ── users by condition");
});

test("named enums, collations, BY DEFAULT identities and long names read correctly in inspect", () => {
  const model = schema({
    accounts: table({
      id: int.auto.byDefault,
      role: oneOf("USER", "ADMIN").typeName("Role").default("USER"),
      email: text.collate("C").unique,
      name: varchar(200).collate("en-x-icu"),
      customerSubscriptionBillingAdjustmentReference: text,
      amount: int,
    })
      .named("customer_subscription_billing_adjustments_for_long_names")
      .checks((accounts) => ({
        positiveAmountForTheCustomerSubscription: sql`${accounts.amount} > 0`,
      })),
  }).$snapshot();
  const accounts = model.tables[0]!;
  const columns = inspectEntries(accounts, "Columns");

  expect(columns.find((entry) => entry.name === "role")).toMatchObject({
    kind: 'enum "Role"',
    description: expect.stringContaining("Values: USER · ADMIN"),
  });
  expect(columns.find((entry) => entry.name === "email")).toMatchObject({
    kind: 'text collate "C"',
    badges: ["UNIQUE"],
  });
  // A collation is searchable like any other column detail.
  expect(matchingTables(model, "en-x-icu")).toEqual([accounts]);
  expect(inspectEntries(accounts, "Checks")[0]!.name).toHaveLength(63);

  const listing = stripVTControlCharacters(formatSchema(model)).split("\n");
  expect(listing).toContain(
    "  ├─ id                   integer · primary key · identity by default",
  );
  expect(listing).toContain(
    '  ├─ role                 enum "Role" · default "USER"',
  );
  expect(listing).toContain(
    '  ├─ email                text collate "C" · unique',
  );
  // A name longer than the column runs past it instead of widening the rest.
  expect(listing).toContain(
    "  ├─ customerSubscriptionBillingAdjustmentReference text",
  );
  expect(listing).toContain("  └─ amount               integer");
});

test("a modified column shows the collation, identity or enum type that changed", () => {
  const before = schema({
    users: { id: int.auto, email: text, role: oneOf("a", "b") },
  }).$snapshot();
  const after = schema({
    users: {
      id: int.auto.byDefault,
      email: text.collate("C"),
      role: oneOf("a", "b").typeName("Role"),
    },
  }).$snapshot();

  expect(formatDiff(diffSchemas(before, after)).split("\n")).toEqual([
    "  ~ users",
    "    ~ id                   integer · identity → integer · identity by default",
    '    ~ email                text → text collate "C"',
    "    ~ role                 enum users_role_enum → enum Role",
    "",
    "    ~ enum users_role_enum → Role: a | b → a | b",
    "  1 tables changed · 3 SQL statements",
  ]);
});

test("SQL line numbers follow source lines when long lines wrap", () => {
  expect(
    numberedLines("SELECT 1\nFROM a_rather_long_table_name\n;", 12, (label) =>
      label.replace(/ /g, "."),
    ),
  ).toEqual([
    "..1  SELECT 1",
    "..2  FROM a_rathe",
    "...  r_long_table",
    "...  _name",
    "..3  ;",
  ]);
});

test("the compact dashboard header fits a short, narrow terminal", () => {
  const { rows, columns } = process.stdout;
  Object.assign(process.stdout, { rows: 10, columns: 24 });

  try {
    const header = formatDashboard({
      address: "PostgreSQL · 127.0.0.1:55474/a_long_database_name",
      connection: "connected",
      snapshot: undefined,
      migrations: "",
      pending: 0,
      changes: 0,
      config: "symmetria.config.ts",
    });

    for (const line of header.split("\n")) {
      expect(stripVTControlCharacters(line).length).toBeLessThanOrEqual(22);
    }
  } finally {
    Object.assign(process.stdout, { rows, columns });
  }
});
